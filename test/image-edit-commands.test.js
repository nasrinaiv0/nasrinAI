import test from 'node:test';
import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { execFileSync } from 'node:child_process';
import vm from 'node:vm';
import { commandMenu, imageEditCount, skillCatalog } from '../src/skill-commands.js';
import { buildTestApp, serve } from './helpers.js';

const catalog = JSON.parse(readFileSync(new URL('../config/image-edit-commands.json', import.meta.url), 'utf8'));
const CORE = ['clone', 'blur', 'remove-background', 'upscale', 'image', 'video', 'rewrite', 'translate', 'summarize', 'shorten', 'expand', 'proofread', 'explain', 'debug', 'review', 'research', 'compare', 'plan', 'brainstorm', 'email', 'code', 'analyze', 'automate', 'search', 'browse', 'remember', 'recall', 'library', 'file', 'document', 'connect'];

test('over a thousand unique picture-editing commands, each with a concrete edit instruction', () => {
  assert.ok(imageEditCount() >= 1000, 'thousand-plus commands');
  const names = catalog.commands.map((c) => c.command);
  assert.equal(new Set(names).size, names.length, 'unique');
  const skills = new Set(skillCatalog().commands.map((c) => c.command));
  for (const c of catalog.commands) {
    assert.match(c.command, /^[a-z0-9][a-z0-9-]{0,47}$/);
    assert.equal(c.kind, 'image-edit');
    assert.match(c.prompt, /attached/, c.command + ' edits the attached photo');
    assert.ok(c.prompt.length <= 600);
    assert.equal(CORE.includes(c.command), false, c.command + ' must not shadow a core command');
    assert.equal(skills.has(c.command), false, c.command + ' must not shadow a skill command');
  }
  for (const n of ['bg-beach-at-sunset', 'style-watercolor-painting', 'look-black-and-white', 'remove-people-in-the-background', 'brighten-slight', 'crop-square', 'hair-bob-cut', 'make-sticker-with-white-outline']) assert.ok(names.includes(n), n);
});

test('the catalog file is generated by the build script and up to date', () => {
  const before = readFileSync(new URL('../config/image-edit-commands.json', import.meta.url), 'utf8');
  execFileSync(process.execPath, [new URL('../scripts/build-image-edit-commands.js', import.meta.url).pathname], { stdio: 'ignore' });
  assert.equal(readFileSync(new URL('../config/image-edit-commands.json', import.meta.url), 'utf8'), before, 'run: node scripts/build-image-edit-commands.js');
});

test('the app recognises a registered picture-edit command as a photo edit with its instruction', () => {
  const sandbox = {};
  vm.runInNewContext(readFileSync(new URL('../public/creative-intent.js', import.meta.url), 'utf8'), sandbox);
  const ci = sandbox.NasrinCreativeIntent;
  assert.equal(ci.parseShortcut('/bg-beach-at-sunset'), null, 'unknown until the catalog loads');
  ci.registerImageEdits(catalog.commands);
  const s = ci.parseShortcut('/BG-Beach-At-Sunset keep my hat');
  assert.equal(s.capability, 'image');
  assert.equal(s.requiresPhoto, true);
  assert.equal(s.args, 'keep my hat');
  assert.match(s.prompt, /Replace the background of the attached photo with beach at sunset/);
  assert.equal(ci.parseShortcut('/blur').name, 'blur', 'core commands still win');
  ci.registerImageEdits([{ command: 'blur', kind: 'image-edit', prompt: 'evil' }, { command: 'Bad Name', kind: 'image-edit', prompt: 'x' }]);
  assert.equal(ci.parseShortcut('/blur').prompt, undefined, 'a catalog entry can never replace a core command');
});

test('the public command menu serves skills and picture edits', async () => {
  const built = buildTestApp();
  const srv = await serve(built.app);
  try {
    const body = await (await fetch(srv.url + '/v1/commands')).json();
    assert.equal(body.commands.length, commandMenu().commands.length);
    assert.ok(body.commands.some((c) => c.kind === 'image-edit'));
    assert.ok(body.commands.some((c) => c.kind === 'skill'));
  } finally { await srv.close(); }
});
